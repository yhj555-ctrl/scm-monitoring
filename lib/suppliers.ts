export type RiskTier = "상" | "중" | "하";

export function gradeToRisk(grade: SupplierGrade): RiskTier {
  if (grade === "위험 (Risk)" || grade === "위험 (Risk) - 과락" || grade === "점수 오류") return "상";
  if (grade === "유의 (Caution)") return "중";
  return "하";
}

export function riskCounts() {
  return suppliers.reduce(
    (acc, s) => {
      const tier = gradeToRisk(s.grade);
      acc[tier] += 1;
      return acc;
    },
    { 상: 0, 중: 0, 하: 0 } as Record<RiskTier, number>
  );
}

/** 사업자번호 정규화(숫자만) — DART 매칭 등에 사용. */
export function normalizeBizNo(bizNo: string | null): string | null {
  if (!bizNo) return null;
  const digits = bizNo.replace(/[^0-9]/g, "");
  return digits.length === 10 ? digits : null;
}
